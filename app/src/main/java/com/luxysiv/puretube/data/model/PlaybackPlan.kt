package com.luxysiv.puretube.data.model

/**
 * Một ứng viên nguồn phát mà trình phát có thể thử: DASH (MPD), HLS (live/VOD)
 * hoặc progressive MP4 (video+audio trong một file).
 *
 * [height] chỉ có giá trị với progressive MP4 — mỗi file chỉ chứa đúng một
 * chất lượng. [isAdaptive] đánh dấu DASH/HLS: manifest chứa nhiều track video
 * nên ExoPlayer có thể đổi chất lượng ngay khi đang phát bằng track selection.
 */
data class PlaybackSource(
    val uri: String,
    val mimeType: String? = null,
    val height: Int? = null,
    val isAdaptive: Boolean = false
)

/**
 * Một track phụ đề tải kèm (side-loaded) cho ExoPlayer.
 *
 * [mimeType] là MIME mà Media3 hiểu (text/vtt, application/ttml+xml,
 * application/x-subrip...). [isDefault] đánh dấu track nên chọn trước khi người
 * dùng bật phụ đề (thường là bản không tự động, cùng ngôn ngữ thiết bị).
 */
data class PlaybackSubtitle(
    val uri: String,
    val mimeType: String,
    val languageTag: String = "",
    val label: String = "",
    val isAutoGenerated: Boolean = false,
    val isDefault: Boolean = false
)

/**
 * Kế hoạch phát cho một video, do InnerTube `player` trả về.
 *
 * [candidates] sắp xếp theo thứ tự ưu tiên; trình phát ExoPlayer thử lần lượt
 * (DASH → HLS → progressive), hết ứng viên thì báo lỗi cho người dùng.
 *
 * [qualities] là danh sách chiều cao video thật (720, 1080...) để UI cho chọn
 * chất lượng; rỗng nghĩa là chỉ có "Tự động".
 *
 * [subtitles] là các track phụ đề tải kèm. YouTube không nhúng phụ đề vào luồng
 * progressive/DASH mà trả URL riêng, nên phải gắn vào [MediaItem] thì nút CC
 * mới có dữ liệu để bật.
 */
data class PlaybackPlan(
    val candidates: List<PlaybackSource>,
    val isLive: Boolean = false,
    val qualities: List<Int> = emptyList(),
    val subtitles: List<PlaybackSubtitle> = emptyList()
) {
    /** Có ít nhất một manifest DASH/HLS để đổi chất lượng bằng track selection. */
    val hasAdaptiveSource: Boolean
        get() = candidates.any { it.isAdaptive }

    /**
     * Quy đổi mức người dùng chọn sang mức **thật sự có** trong video.
     *
     * - [requested] null/<= 0 (tự động) → mức cao nhất đang có.
     * - Có mức thấp hơn hoặc bằng yêu cầu → mức cao nhất trong số đó.
     * - Video không có mức nào thấp hơn (ví dụ chọn 144p nhưng chỉ có 240p)
     *   → mức thấp nhất hiện có, thay vì để track selector tắt hình.
     *
     * Nhờ vậy UI luôn chọn đúng chip đang phát và engine không đặt giới hạn
     * chiều cao mà nguồn không đáp ứng được.
     */
    fun resolveHeight(requested: Int?): Int? {
        val available = qualities
            .asSequence()
            .filter { it > 0 }
            .distinct()
            .sortedDescending()
            .toList()
        if (available.isEmpty()) return requested?.takeIf { it > 0 }
        val target = requested?.takeIf { it > 0 } ?: return available.first()
        return available.firstOrNull { it <= target } ?: available.last()
    }

    /**
     * Chọn ứng viên ban đầu theo mức chất lượng người dùng đã lưu.
     *
     * - Có DASH/HLS: luôn dùng manifest, việc chọn đúng chiều cao do
     *   `TrackSelectionParameters` đảm nhiệm.
     * - Chỉ có progressive MP4: mỗi file là một chất lượng cố định, nên phải
     *   chọn đúng file. [height] null/<= 0 nghĩa là tự động (file cao nhất).
     */
    fun candidateIndexFor(height: Int?): Int {
        if (candidates.isEmpty()) return 0
        val adaptiveIndex = candidates.indexOfFirst { it.isAdaptive }
        if (adaptiveIndex >= 0) return adaptiveIndex

        val requested = height?.takeIf { it > 0 }
        if (requested == null) {
            return candidates.indexOfFirst { it.height != null }.let { if (it >= 0) it else 0 }
        }

        var bestIndex = -1
        var bestHeight = -1
        candidates.forEachIndexed { index, source ->
            val sourceHeight = source.height ?: return@forEachIndexed
            if (sourceHeight <= requested && sourceHeight > bestHeight) {
                bestHeight = sourceHeight
                bestIndex = index
            }
        }
        if (bestIndex >= 0) return bestIndex

        // Không có file nào thấp hơn mức chọn (hiếm): dùng file thấp nhất còn
        // lại thay vì để track selector tắt hẳn hình.
        var lowestIndex = -1
        var lowestHeight = Int.MAX_VALUE
        candidates.forEachIndexed { index, source ->
            val sourceHeight = source.height ?: return@forEachIndexed
            if (sourceHeight < lowestHeight) {
                lowestHeight = sourceHeight
                lowestIndex = index
            }
        }
        return if (lowestIndex >= 0) lowestIndex else 0
    }
}

/**
 * Dữ liệu phục vụ phát một video, lấy trong CÙNG một lần resolve (`player` + `next`):
 * kế hoạch phát + danh sách video liên quan thật (để phát tiếp / gợi ý)
 * + thông tin chi tiết (mô tả đầy đủ, lượt xem/thích...) cho trang xem.
 */
data class PlaybackData(
    val plan: PlaybackPlan?,
    val related: List<VideoItem> = emptyList(),
    val details: VideoDetails? = null
)
